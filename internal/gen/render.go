// Every file this package writes is rendered by a hand-written function here
// rather than by marshalling a Go struct or running a template.
//
// Two reasons, and they are different from each other.
//
// The Go source is hand-written because it has to *read* like Go source. A
// `text/template` would put a second language between a person debugging the
// generated setup and the person who wrote the generator, and its errors name a
// line in a string nobody can diff. `internal/dev/render.go` writes the compose
// document the same way and for the same reason.
//
// The JSON declaration is NOT hand-written, and the reason is the opposite one:
// `encoding/json` on a struct emits fields in declaration order, deterministically,
// and the alternative is fifty lines of builder calls to produce the same bytes
// with fifty more places to put a comma in the wrong place. The rule that makes
// the compose document hand-written — that a general YAML encoder would order
// keys by its own map — has no JSON equivalent, so the argument does not
// transfer.
//
// Neither renderer reads a clock, a random source or a map's iteration order.
// Every list below comes out of a slice the contract package built in schema
// order, so two runs over one manifest produce identical bytes and the drift
// gate's diff is a diff of two manifests.

// writer builds a generated file, and it has exactly two methods so that a `%`
// in generated code can never be mistaken for a substitution in the generator.
//
// This is not a style preference and it is the result of a bug. The first draft
// of these renderers was one `fmt.Fprintf` per block, and the emitted setup
// contains `fmt.Errorf("telemetry: a span name has at most %d segment(s)…")` —
// so the generator's own format string had three arguments for six verbs, `go
// vet` caught it, and the fix was to add `%%` in six places. That works until
// one is missed, and a missed one does not fail the build: it silently consumes
// the next argument and emits a generated file whose error messages are wrong.
//
// `text` writes bytes verbatim. `at` substitutes, and its format is always a
// one-verb literal with one argument, so there is no counting to do and no way
// for a generated `%d` to reach it.
type writer struct {
	b bytes.Buffer
}

func (w *writer) text(s string) { w.b.WriteString(s) }

func (w *writer) at(format string, arg any) { fmt.Fprintf(&w.b, format, arg) }

func (w *writer) bytes() []byte { return w.b.Bytes() }

