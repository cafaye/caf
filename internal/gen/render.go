// renderGoSource writes the generated OpenTelemetry setup.
func renderGoSource(manifest contract.Manifest, spec contract.TelemetrySpec, variable string) []byte {
	var w writer

	writeGeneratedHeader(&w, manifest, spec, goSourcePath,
		"the OpenTelemetry setup: the attribute allowlists, the prohibition on\n"+
			"// unbounded identifiers, the resource attributes, the span-name bound,\n"+
			"// the endpoint variable and the no-op path.")

	w.text(`
package telemetry

import (
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

// The three signals, named as core names them. There is no fourth: a signal
// nobody has allowlisted has no default-deny list to fall back to, and one
// named here without a list would be a signal whose contents are undefined.
const (
	SignalTraces  = "traces"
	SignalMetrics = "metrics"
	SignalLogs    = "logs"
)
`)

	renderIdentity(&w, manifest, spec, variable)
	renderEndpoint(&w, spec, variable)
	renderAllowlists(&w, spec)
	renderProhibition(&w, spec)
	renderSpanNaming(&w, spec)
	renderErrorTypes(&w, spec)
	renderChecks(&w, spec)

	return w.bytes()
}

// writeGeneratedHeader writes the comment every generated file opens with. It is
// one function because two files repeat it and two copies of a provenance
// header is one of them wrong.
//
// The "DO NOT EDIT" line is not a request. It is there because the drift gate is
// a byte comparison against what the generator would write today, and a
// hand-edited file fails that gate — which is correct: a hand-edited generated
// file and a regenerated one are two files, and nothing in the tree can say
// which of them the project meant.
func writeGeneratedHeader(w *writer, manifest contract.Manifest, spec contract.TelemetrySpec, path, what string) {
	w.text(`// Code generated by ` + "`caf gen telemetry`" + `. DO NOT EDIT.
//
// `)
	w.text(what)
	w.text(`
//
// WHAT IS DERIVED AND WHAT IS NOT, because a generated file that does not say
// which half of it is an instruction from core is an instruction from whoever
// last touched the generator.
//
// Derived, read out of the cafaye core telemetry contract vendored at
// cafaye/internal/contract/schemas/telemetry/ and pinned there by sha256:
// the three per-signal attribute allowlists and their value vocabularies, the
// names core refuses as a measurement attribute, the resource attributes, the
// error.type vocabulary, the span-name grammar, the `)
	w.at("%s", spec.Endpoint.NoOpImplementedBy)
	w.text(` switch, the three per-signal switches, and the four negative
// properties of the no-op path.
//
// From the manifest: the service name (`)
	w.at("%q", manifest.ServiceName())
	w.text(`) and the language, which is what decided that
// Go was the right file to write.
//
// Written down here, and not derived from anything, because core's schemas
// constrain the shape of these values and do not state them: the namespace
// every cafaye service groups under (`)
	w.at("%q", namespace)
	w.text(`), and the address of the
// collector that ships with the local stack (`)
	w.at("%q", spec.Endpoint.Default)
	w.text(`). core's docs/observability.md and its
// examples/valid/telemetry/otel-endpoint.json agree on both; they are the
// fleet's documented values, not this generator's invention.
//
// To change any of it, change cafaye.yml or change core, and run
// ` + "`caf gen telemetry -force`" + ` again. The test beside this file is
// the thing that notices you did not.
`)
}

