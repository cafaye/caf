// renderStringList writes a string slice as quoted elements, one per line, at
// the given depth.
//
// Depth is a parameter because the emitted file has to be gofmt-canonical — a
// generated file that fails `gofmt -l` in the service that adopts it is a file
// that fails the one lint every Go repository in this fleet runs, and "run
// gofmt on it after generating" is not an answer a generator can give. Nesting a
// `[]string{…}` inside a map literal indents its elements one level deeper, and
// getting that wrong is invisible until somebody runs the linter.
//
// One per line rather than one long line because a list of thirteen classes read
// on one line is a list of thirteen things a reviewer scrolls past, and the
// allowlist this file emits is reviewed every time core bumps it.
func renderStringList(w *writer, values []string, depth int) {
	indent := strings.Repeat("\t", depth)
	for _, value := range values {
		w.text(indent)
		w.at("%q,\n", value)
	}
}

// allowlistNames is one signal's attribute names, in schema order.
func allowlistNames(signal contract.Signal) []string {
	names := make([]string, 0, len(signal.Allowlist))
	for _, attribute := range signal.Allowlist {
		names = append(names, attribute.Name)
	}
	return names
}

// resourceNames is the resource attribute list, read off the traces signal.
//
// One signal rather than three, and the choice is checked rather than assumed:
// `TestTheResourceAttributeListIsTheSameOnEverySignal` in internal/contract is
// what proves core's three copies are still one list. Reading one of them and
// relying on that test is the whole difference between deriving a value once and
// deriving it three times and hoping they agree.
func resourceNames(spec contract.TelemetrySpec) []string {
	names := make([]string, 0, len(spec.Traces.Resource))
	for _, attribute := range spec.Traces.Resource {
		names = append(names, attribute.Name)
	}
	return names
}

// schemaFileFor names the vendored schema a signal's allowlist came from, and
// appears in the generated file so a reader can go and read the contract rather
// than trust the generator.
func schemaFileFor(signal string) string {
	switch signal {
	case "metrics":
		return "metrics.schema.json"
	default:
		return signal + ".schema.json"
	}
}

// capitalise upper-cases the first letter of a lowercase word core uses as an
// identifier — a signal name, a JSON type, a schema stem — so the emitted
// identifier reads as a Go identifier rather than as the string it came from.
//
// A function here rather than the one a generated file might declare: this one
// runs in caf, on a name read out of a schema. They happen to do the same thing
// and giving them one name would suggest a relationship that does not exist.
func capitalise(word string) string {
	if word == "" {
		return ""
	}
	return strings.ToUpper(word[:1]) + word[1:]
}
