// endpointDeclaration is the document written to telemetry/otel-endpoint.json.
//
// A struct rather than a map, and that is the whole reason this file is rendered
// with `encoding/json`: a struct's fields marshal in declaration order, so the
// emitted document's key order is a fact of this source file and not of a map
// iteration. core's own examples are written in the same order, so a diff
// between a generated declaration and the example beside it in core's tree reads
// as a difference of values rather than of layout.
type endpointDeclaration struct {
	Service            string          `json:"service"`
	Signals            []string        `json:"signals"`
	Endpoint           endpointBlock   `json:"endpoint"`
	NoOp               noOpBlock       `json:"noOp"`
	DisabledBy         disabledByBlock `json:"disabledBy"`
	ResourceAttributes []string        `json:"resourceAttributes"`
	Notes              string          `json:"notes,omitempty"`
}

type endpointBlock struct {
	Variable string `json:"variable"`
	Default  string `json:"default"`
	Required bool   `json:"required"`
}

type noOpBlock struct {
	ImplementedBy string `json:"implementedBy"`
	Buffering     string `json:"buffering"`
	Retry         string `json:"retry"`
	Warnings      string `json:"warnings"`
	StartupCost   string `json:"startupCost"`
}

type disabledByBlock struct {
	Global  string `json:"global"`
	Traces  string `json:"traces"`
	Metrics string `json:"metrics"`
	Logs    string `json:"logs"`
}

// renderEndpointDeclaration writes the declaration and returns its bytes.
//
// `protocol` and `timeoutMs` are deliberately absent. Both are optional in
// core's schema, both are a per-service choice, and neither is derivable: the
// schema constrains the SHAPE of `default` with a pattern and a format without
// stating the value, and `timeoutMs`'s `maximum` is a ceiling rather than a
// default. Emitting a value for either would be a guess dressed as a derivation,
// and a guess in a file an operator writes a collector config against is the
// kind that gets copied.
func renderEndpointDeclaration(manifest contract.Manifest, spec contract.TelemetrySpec, variable string) ([]byte, error) {
	endpoint := spec.Endpoint

	// Short on purpose, and the cap is what decided it. core's schema puts
	// `notes` at 400 characters and validating the rendered document against the
	// very schema it was derived from is how that number was discovered rather
	// than guessed — the first draft of this sentence was 445 and the generator
	// refused to write its own output. The four negative properties of the no-op
	// do not need restating here: they are in the `noOp` block below, where a
	// collector config can read them as fields rather than as prose.
	notes := fmt.Sprintf("The collector is the default value of %s, not a requirement: unset it and the "+
		"no-op below is free. The verifier is internal/telemetry/telemetry_test.go.", variable)
	if derived := endpointVariableNote(manifest.ServiceName()); derived != "" {
		notes += " " + derived
	}

	declaration := endpointDeclaration{
		Service: manifest.ServiceName(),
		// All three, and not a subset. core's own note on this field says all three
		// are in scope for a service and a subset is for a component, and a
		// manifest cannot describe a component — so a subset here would be this
		// generator deciding which signals the service cares about, which is not a
		// fact it has.
		Signals: []string{"traces", "metrics", "logs"},
		Endpoint: endpointBlock{
			Variable: variable,
			Default:  endpoint.Default,
			Required: endpoint.Required,
		},
		NoOp: noOpBlock{
			ImplementedBy: endpoint.NoOpImplementedBy,
			Buffering:     endpoint.NoBuffering,
			Retry:         endpoint.NoRetry,
			Warnings:      endpoint.NoWarnings,
			StartupCost:   endpoint.NoStartupCost,
		},
		DisabledBy: disabledByBlock{
			Global:  endpoint.DisabledByGlobal,
			Traces:  endpoint.DisabledByTraces,
			Metrics: endpoint.DisabledByMetrics,
			Logs:    endpoint.DisabledByLogs,
		},
		ResourceAttributes: resourceNames(spec),
		Notes:              notes,
	}

	var buffer bytes.Buffer
	encoder := json.NewEncoder(&buffer)
	// No HTML escaping. `encoding/json` escapes <, > and & by default, which would
	// put a six-character escape in a file a person reads; nothing here needs it
	// and a generated file nobody can read is a file nobody checks.
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(declaration); err != nil {
		return nil, fmt.Errorf("caf gen telemetry: render the endpoint declaration: %w", err)
	}
	return buffer.Bytes(), nil
}

